"""Memory Flush 用的 LLM 提示词，与算法分离以免单文件过长。"""

USER_EXTRACT_PROMPT = """你是一个记忆提取助手。分析下面的对话，提取关于**用户**的新信息。

只提取对话中用户**明确表达**或**强烈暗示**的信息，不要推断。
格式输出为 JSON 数组，每个元素包含：
- "field"：信息所属字段（如"姓名"、"职业"、"所在地"、"偏好-XX"、"关注标的"等）
- "value"：具体内容（一句话）
- "confidence"："high" 或 "medium"

如果没有任何新信息，返回空数组 []。

对话内容：
{conversation}"""

USER_MD_UPDATE_PROMPT = """你是一个文档更新助手。根据提取到的新信息，更新下面的 USER.md。

规则：
1. 字段已存在且内容一致则保持
2. 字段已存在但内容更新则替换
3. 新字段添加到对应章节
4. "（尚未告知）"或"（暂无记录）"有新信息则替换
5. 只输出更新后的完整 USER.md，不要其他说明

当前 USER.md：
{current_user_md}

新信息（JSON）：
{new_info}"""

MEMORY_EXTRACT_PROMPT = """你是一个记忆提取助手。分析下面的对话，提取值得**长期记忆**的信息。

标准（满足其一即可）：
- 明确偏好（超出 USER.md 个人信息的具体偏好）
- 值得记录的事件或决定
- 用户分享的领域见解

每条格式（JSON 数组）：
- "category"：preference | fact | event | decision
- "title"：一句话标题（15字以内）
- "content"：详细内容（2~4句话）

没有值得记录的内容则返回 []。

对话内容：
{conversation}"""

SESSION_SUMMARY_PROMPT = """根据下面的对话写一段**今日会话摘要**（近端记忆，不是长期档案）。

要求：3~6 句中文；保留对接下来 1~2 天仍有用的细节；不要捏造；不要 JSON；不要 markdown 标题；只输出摘要正文。

对话内容：
{conversation}"""

COMPACTION_PROMPT = """把下面旧记忆条目压缩合并为更简洁的摘要。

规则：合并同类、去掉重复、保留最新、不要丢失重要内容。
输出与输入相同的 JSON 数组，条目数应明显少于输入。

待压缩的条目：
{entries}"""
